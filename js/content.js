// 의료·진단·치료 표현은 쓰지 않는다 (웰니스 범위). {n} = 수달 이름

// 받침에 따라 조사 고르기: josa('몽이', '이/가') → '몽이가'
export function josa(word, pair) {
  const [a, b] = pair.split('/');
  const last = word.charCodeAt(word.length - 1);
  if (last < 0xac00 || last > 0xd7a3) return word + b;
  const has = (last - 0xac00) % 28 !== 0;
  return word + (has ? a : b);
}

// 문장 안의 {n이}, {n은}, {n을}, {n과}, {n} 을 이름+조사로 바꾼다
export function fill(text, name) {
  return text
    .replaceAll('{n이}', josa(name, '이/가'))
    .replaceAll('{n은}', josa(name, '은/는'))
    .replaceAll('{n을}', josa(name, '을/를'))
    .replaceAll('{n과}', josa(name, '과/와'))
    .replaceAll('{n}', name);
}

